/**
 * ══════════════════════════════════════════════════════════════
 *  统一受礼人关系分类器 (Airtight Relationship Classifier)
 *  —— 严格确定优先级，防止“女朋友/妻子”中的“女”误判为“孩子”
 * ══════════════════════════════════════════════════════════════
 */

export function classifyRelationship(recipient = '') {
  const r = String(recipient || '').trim()

  // 1. 伴侣 / 恋人（最高优先级判定，彻底避免“女朋友/妻子”误伤）
  if (/(女朋友|妻子|老婆|女友|男朋友|丈夫|老公|男友|对象|爱人|伴侣|情侣|暗恋|太太|先生|另一半)/.test(r)) {
    return 'lover'
  }

  // 2. 父母 / 长辈
  if (/(父母|长辈|爸爸|妈妈|老爸|老妈|老两口|公公|婆婆|岳父|岳母|爷爷|奶奶|外公|外婆|姥姥|姥爷|舅舅|姑姑|伯父|伯母|长辈)/.test(r)) {
    return 'elder'
  }

  // 3. 孩子 / 晚辈
  if (/(孩子|晚辈|儿子|女儿|侄子|侄女|外甥|外甥女|宝宝|婴儿|幼儿|小学生|初中生|高中生|弟弟|妹妹|小朋友|小孩|学生)/.test(r)) {
    return 'junior'
  }

  // 4. 同事 / 职场
  if (/(同事|领导|上司|下属|老板|客户|商务|合伙人)/.test(r)) {
    return 'work'
  }

  // 5. 默认归为朋友
  return 'friend'
}
